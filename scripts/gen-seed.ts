/**
 * Generates supabase/seed.sql (public content) and supabase/local/demo.sql (fictional clients,
 * LOCAL DEMO ONLY) from the typed seed files, so there is one source of truth.
 * Run: node scripts/gen-seed.ts
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { seedArticles } from '../lib/content/seed/articles.ts';
import { seedFoods, type SeedFood } from '../lib/content/seed/foods.ts';
import { seedRecipes } from '../lib/content/seed/recipes.ts';
import { seedSettings } from '../lib/content/seed/settings.ts';
import { seedUid as uid } from '../lib/content/seed/ids.ts';

const root = path.resolve(import.meta.dirname, '..');
const LOCALES = ['tr', 'en', 'fr', 'ar'] as const;

const q = (s: string | null | undefined) => (s == null ? 'null' : `'${s.replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (v: readonly string[]) => `${q(`{${v.map((x) => `"${x}"`).join(',')}}`)}::text[]`;
const n = (v: number | null | undefined) => (v == null ? 'null' : String(v));

const foodByKey = new Map<string, SeedFood>(seedFoods.map((f) => [f.key, f]));

function chunk(lines: string[]): string {
  return lines.join(',\n    ');
}

