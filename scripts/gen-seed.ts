function foodMacros(key: string, grams: number) {
  const f = foodByKey.get(key)!;
  const k = grams / 100;
  return { kcal: f.kcal * k, p: f.p * k, c: f.c * k, f: f.f * k, fib: f.fib * k };
}

function recipePerServing(key: string) {
  const r = seedRecipes.find((x) => x.key === key)!;
  const t = { kcal: 0, p: 0, c: 0, f: 0, fib: 0 };
  for (const ing of r.ingredients) {
    if (ing.optional) continue;
    const m = foodMacros(ing.food, ing.grams);
    t.kcal += m.kcal;
    t.p += m.p;
    t.c += m.c;
    t.f += m.f;
    t.fib += m.fib;
  }
  return {
    kcal: t.kcal / r.servings,
    p: t.p / r.servings,
    c: t.c / r.servings,
    f: t.f / r.servings,
    fib: t.fib / r.servings,
  };
}

