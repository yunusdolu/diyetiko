// seed.sql
// ---------------------------------------------------------------------------
const out: string[] = [];
out.push(`-- GENERATED by scripts/gen-seed.ts — edit lib/content/seed/*.ts instead.
-- Public content only (foods, recipes, guides, site settings). Owned by the first auth user,
-- so create the dietitian account BEFORE running this (see README).
do $seed$
declare
  v_owner uuid;
begin
  select id into v_owner from public.profiles where role = 'dietitian' order by created_at limit 1;
  if v_owner is null then
    raise exception 'No dietitian account found. Create the dietitian account first (KURULUM.md → Adım 4).';
  end if;
`);

out.push(`  insert into public.foods (id, owner_id, key, category, kcal, protein_g, carb_g, fat_g, fiber_g, flags, units, review_status, source) values
    ${chunk(
      seedFoods.map(
        (f) =>
          `(${q(uid(`food:${f.key}`))}, v_owner, ${q(f.key)}, ${q(f.category)}, ${n(f.kcal)}, ${n(f.p)}, ${n(f.c)}, ${n(f.f)}, ${n(f.fib)}, ${arr(f.flags ?? [])}, ${j(f.units ?? [])}, 'needs_review', 'seed: approximate reference values — verify')`,
      ),
    )}
  on conflict (owner_id, key) do nothing;
`);

out.push(`  insert into public.food_translations (food_id, locale, owner_id, name, translation_status) values
    ${chunk(
      seedFoods.flatMap((f) =>
        LOCALES.map(
          (l) =>
            `(${q(uid(`food:${f.key}`))}, '${l}', v_owner, ${q(f.names[l])}, '${l === 'tr' ? 'reviewed' : 'needs_review'}')`,
        ),
      ),
    )}
  on conflict (food_id, locale) do nothing;
`);

out.push(`  insert into public.recipes (id, owner_id, published, published_at, illustration, prep_min, cook_min, servings, meal_types) values
    ${chunk(
      seedRecipes.map(
        (r, i) =>
          `(${q(uid(`recipe:${r.key}`))}, v_owner, true, now() - interval '${i} days', ${q(r.illustration)}, ${r.prepMin}, ${r.cookMin}, ${r.servings}, ${arr(r.mealTypes)})`,
      ),
    )}
  on conflict (id) do nothing;
`);

out.push(`  insert into public.recipe_translations (recipe_id, locale, owner_id, slug, title, summary, steps, tips, translation_status) values
    ${chunk(
      seedRecipes.flatMap((r) =>
        LOCALES.map((l) => {
          const t = r.text[l];
          return `(${q(uid(`recipe:${r.key}`))}, '${l}', v_owner, ${q(t.slug)}, ${q(t.title)}, ${q(t.summary)}, ${j(t.steps)}, ${q(t.tips ?? null)}, 'needs_review')`;
        }),
      ),
    )}
  on conflict (recipe_id, locale) do nothing;
`);

out.push(`  insert into public.recipe_ingredients (id, owner_id, recipe_id, food_id, grams, unit_key, unit_qty, optional, position) values
    ${chunk(
      seedRecipes.flatMap((r) =>
        r.ingredients.map((ing, i) => {
          if (!foodByKey.has(ing.food)) throw new Error(`Unknown food ${ing.food} in ${r.key}`);
          return `(${q(uid(`ri:${r.key}:${i}`))}, v_owner, ${q(uid(`recipe:${r.key}`))}, ${q(uid(`food:${ing.food}`))}, ${n(ing.grams)}, ${q(ing.unit ?? null)}, ${n(ing.qty)}, ${ing.optional ? 'true' : 'false'}, ${i})`;
        }),
      ),
    )}
  on conflict (id) do nothing;
`);

out.push(`  insert into public.articles (id, owner_id, published, published_at, illustration, category, reading_min, sources) values
    ${chunk(
      seedArticles.map(
        (a, i) =>
          `(${q(uid(`article:${a.key}`))}, v_owner, true, now() - interval '${i * 3} days', ${q(a.illustration)}, ${q(a.category)}, ${a.readingMin}, ${j(a.sources)})`,
      ),
    )}
  on conflict (id) do nothing;
`);

out.push(`  insert into public.article_translations (article_id, locale, owner_id, slug, title, excerpt, body, translation_status) values
    ${chunk(
      seedArticles.flatMap((a) =>
        LOCALES.map((l) => {
          const t = a.text[l];
          return `(${q(uid(`article:${a.key}`))}, '${l}', v_owner, ${q(t.slug)}, ${q(t.title)}, ${q(t.excerpt)}, ${q(t.body)}, 'needs_review')`;
        }),
      ),
    )}
  on conflict (article_id, locale) do nothing;
`);

out.push(`  insert into public.site_settings (key, owner_id, is_public, data) values
    ${chunk(Object.entries(seedSettings).map(([k, v]) => `(${q(k)}, v_owner, true, ${j(v)})`))}
  on conflict (key) do nothing;
end $seed$;
`);

writeFileSync(path.join(root, 'supabase', 'seed.sql'), out.join('\n'));

